import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { BENCH_CHAPTERS, benchMemory } from '@/lib/editor-bench/fixture';
import { MODES, SPEEDS, benchRequest, measureKey, measurePrompt, promptReport, type PromptMeasure } from '@/lib/editor-bench/measure';
import { SCENARIOS } from '@/lib/editor-bench/scenarios';

// Offline AI editor benchmark: every question kind on every speed, with and
// without project memory, measured from the exact prompt story-chat would
// send. It fails when a request starts sending more (tokens) or goes somewhere
// else (model, context). `npm run bench:editor:update` records a new baseline
// and report after an intended change.

const BASELINE = fileURLToPath(new URL('./editor-bench/baseline.json', import.meta.url));
const REPORT = fileURLToPath(new URL('./editor-bench/report.md', import.meta.url));
/** Growth allowed before a request counts as a regression. */
const TOLERANCE = 0.05;

type Baseline = Record<string, Pick<PromptMeasure, 'model' | 'context' | 'inputTokens'>>;

const measures = SCENARIOS.flatMap(scenario => SPEEDS.flatMap(speed => MODES.map(mode => measurePrompt(scenario, speed, mode))));

function report() {
  const total = (list: PromptMeasure[]) => Math.round(list.reduce((n, m) => n + m.inputCredits, 0) * 10) / 10;
  const pair = (speed: string, keep: (m: PromptMeasure) => boolean) => {
    const [text, memory] = MODES.map(mode => measures.filter(m => m.speed === speed && m.mode === mode && keep(m)));
    return `${total(text)} → ${total(memory)}`;
  };
  const kinds: [string, (m: PromptMeasure) => boolean][] = [
    ['passage', m => m.kind === 'passage'], ['chapter', m => m.kind === 'chapter'], ['book', m => m.kind === 'book'], ['all', () => true],
  ];
  const summary = SPEEDS.map(speed => `| ${speed} | ${kinds.map(([, keep]) => pair(speed, keep)).join(' | ')} |`);
  return [
    '# AI editor prompt benchmark',
    '',
    'Generated by `npm run bench:editor:update` from the fixture book in `src/lib/editor-bench/fixture.ts` (8 chapters, about 106k characters).',
    'Input only: tokens are estimated at 4 characters each, the way story-chat bills when a provider reports no usage, and credits are for the input before rounding. Output tokens, speed and answer quality need the live benchmark: Admin → AI editor, or `npm run bench:editor:live`.',
    '',
    '## Input credits, text only → with memory',
    '',
    'Passage questions (4) are a review, spelling, reading flow and one book-wide check of a selection ("Is this consistent with earlier chapters?"); chapter questions (3) a review, a brainstorm and a question about the chapter; book questions (8) six fact questions, pacing and plot holes.',
    '',
    '| Speed | Passage | Chapter | Book | All |',
    '|---|---:|---:|---:|---:|',
    ...summary,
    '',
    ...SPEEDS.flatMap(speed => [`## ${speed[0].toUpperCase()}${speed.slice(1)}`, '', promptReport(measures.filter(m => m.speed === speed)), '']),
  ].join('\n');
}

describe('AI editor prompt benchmark', () => {
  it('matches the baseline: same model and context, no more than 5% more tokens', () => {
    if (process.env.UPDATE_EDITOR_BENCH) {
      const baseline: Baseline = Object.fromEntries(measures.map(m => [measureKey(m), { model: m.model, context: m.context, inputTokens: m.inputTokens }]));
      writeFileSync(BASELINE, `${JSON.stringify(baseline, null, 2)}\n`);
      writeFileSync(REPORT, report());
      return;
    }
    expect(existsSync(BASELINE), 'No baseline yet: run npm run bench:editor:update').toBe(true);
    const baseline: Baseline = JSON.parse(readFileSync(BASELINE, 'utf8'));
    const problems: string[] = [];
    for (const m of measures) {
      const key = measureKey(m);
      const before = baseline[key];
      if (!before) { problems.push(`${key}: not in the baseline`); continue; }
      if (m.model !== before.model) problems.push(`${key}: model ${before.model} → ${m.model}`);
      if (m.context !== before.context) problems.push(`${key}: context ${before.context} → ${m.context}`);
      if (m.inputTokens > before.inputTokens * (1 + TOLERANCE)) {
        problems.push(`${key}: ${before.inputTokens} → ${m.inputTokens} input tokens (+${Math.round((m.inputTokens / before.inputTokens - 1) * 100)}%)`);
      }
    }
    expect(problems, 'Run npm run bench:editor:update if these changes are intended').toEqual([]);
  });

  it('gives every question the passages a correct answer depends on', () => {
    const missing = SCENARIOS.flatMap(scenario => SPEEDS.flatMap(speed => MODES.flatMap(mode => {
      const { systemPrompt, messages } = benchRequest(scenario, speed, mode);
      const sent = systemPrompt + messages[0].content;
      return (scenario.evidence || []).filter(text => !sent.includes(text)).map(text => `${scenario.id}|${speed}|${mode}: "${text}"`);
    })));
    expect(missing).toEqual([]);
  });

  it('answers book fact questions from memory with at most half the input', () => {
    for (const m of measures.filter(m => m.mode === 'memory' && m.kind === 'book')) {
      const text = measures.find(t => measureKey(t) === measureKey({ ...m, mode: 'text' }))!;
      const scenario = SCENARIOS.find(s => s.id === m.id)!;
      if (scenario.evidence && !scenario.wholeBook) {
        expect(m.context, m.id).toBe('book-focused');
        expect(m.inputTokens, m.id).toBeLessThan(text.inputTokens * 0.5);
      } else {
        expect(m.context, m.id).toBe('book-full');
      }
    }
  });

  it('adds memory only where it can help, and little of it to passage and chapter questions', () => {
    for (const m of measures.filter(m => m.mode === 'memory' && m.kind !== 'book' && m.context !== 'book-focused')) {
      const text = measures.find(t => measureKey(t) === measureKey({ ...m, mode: 'text' }))!;
      const scenario = SCENARIOS.find(s => s.id === m.id)!;
      // Spelling and reading flow only look at the passage; these questions name nobody.
      if (scenario.prefab === 'spelling-grammar' || scenario.prefab === 'reading-flow' || ['chapter-review', 'chapter-brainstorm'].includes(m.id)) {
        expect(m.inputTokens, measureKey(m)).toBe(text.inputTokens);
      } else {
        expect(m.inputTokens - text.inputTokens, measureKey(m)).toBeLessThanOrEqual(1_600);
      }
    }
    for (const m of measures.filter(m => m.mode === 'memory' && m.context === 'book-full')) {
      expect(m.inputTokens, measureKey(m)).toBe(measures.find(t => measureKey(t) === measureKey({ ...m, mode: 'text' }))!.inputTokens);
    }
  });

  it('only changes the context with memory, never the model or scope', () => {
    for (const m of measures.filter(m => m.mode === 'memory')) {
      const text = measures.find(t => measureKey(t) === measureKey({ ...m, mode: 'text' }))!;
      expect([m.model, m.scope], measureKey(m)).toEqual([text.model, text.scope]);
    }
    for (const scenario of SCENARIOS) {
      expect(benchRequest(scenario, 'thoughtful', 'text').systemPrompt).not.toContain('## Project memory');
    }
  });

  it('starts every request with the same long fixed rules, so providers can cache them', () => {
    const starts = new Map<string, string>();
    for (const scenario of SCENARIOS) for (const speed of SPEEDS) for (const mode of MODES) {
      const { systemPrompt, plan } = benchRequest(scenario, speed, mode);
      const at = systemPrompt.indexOf('\n# This request\n');
      expect(at, measureKey({ id: scenario.id, speed, mode })).toBeGreaterThan(0);
      const fixed = systemPrompt.slice(0, at);
      // Nothing that changes from request to request comes before it.
      for (const changing of ['2026-10-01', '\n## Project memory', '\n## Selected passage\n', '\n## Current chapter', scenario.question]) {
        expect(fixed, `${measureKey({ id: scenario.id, speed, mode })}: ${changing}`).not.toContain(changing);
      }
      expect(fixed.length / 4, measureKey({ id: scenario.id, speed, mode })).toBeGreaterThan(4_000);
      const kind = `${speed}|${scenario.prefab ?? ''}|${plan.scope === 'selection'}`;
      const previous = starts.get(kind);
      if (previous) expect(fixed, kind).toBe(previous); else starts.set(kind, fixed);
    }
  });

  it('has a fixture whose memory quotes come from its chapters', () => {
    for (const chapter of benchMemory().chapters) {
      const content = BENCH_CHAPTERS.find(c => c.id === chapter.id)!.content;
      for (const claim of chapter.claims) expect(content, claim.statement).toContain(claim.quote);
    }
  });
});
